use async_compression::brotli;
use async_compression::tokio::bufread::{BrotliEncoder, GzipEncoder};
use std::error::Error;
use std::fmt::Write as _;
use tokio::fs;
use tokio::fs::File;
use tokio::io::{AsyncWriteExt, BufReader};

const PATH_MAPS: &str = "src/i18n/src/maps.rs";
const PATH_STATIC: &str = "src/i18n/static";

#[tokio::main]
async fn main() -> Result<(), Box<dyn Error>> {
    let _ = fs::create_dir(PATH_STATIC).await;
    let _ = fs::remove_dir_all(format!("{PATH_STATIC}/admin")).await;
    let _ = fs::remove_dir_all(format!("{PATH_STATIC}/common")).await;
    let _ = fs::create_dir(format!("{PATH_STATIC}/admin")).await;
    let _ = fs::create_dir(format!("{PATH_STATIC}/common")).await;

    let mut hashes_map_rs = String::with_capacity(512);

    let mut map_lookup = phf_codegen::Map::new();
    let mut map_br = phf_codegen::Map::new();
    let mut map_gz = phf_codegen::Map::new();
    for (lang, i18n) in rauthy_i18n::build_all_admin() {
        let hash = i18n.content_hash();
        map_lookup.entry(lang.as_str(), format!("{hash:?}"));

        let json = serde_json::to_string(&i18n)?;
        let name = format!("/admin/{lang}_{hash}");
        let name_br = format!("{name}.br");
        let name_gz = format!("{name}.gz");
        write_compress(&name, &name_br, &name_gz, &json).await;

        map_br.entry(hash.clone(), format!("include_bytes!(\"../{name_br}\")"));
        map_gz.entry(hash, format!("include_bytes!(\"../{name_gz}\")"));
    }
    writeln!(
        hashes_map_rs,
        "// DO NOT EDIT - This file is auto-generated by `src/bin/build.rs`\n"
    )?;
    writeln!(
        hashes_map_rs,
        "pub(crate) static HASHES_ADMIN: ::phf::Map<&'static str, &'static str> = {};\n",
        map_lookup.build()
    )?;
    writeln!(
        hashes_map_rs,
        "pub(crate) static I18N_ADMIN_BR: ::phf::Map<&'static str, &'static [u8]> = {};\n",
        map_br.build()
    )?;
    writeln!(
        hashes_map_rs,
        "pub(crate) static I18N_ADMIN_GZ: ::phf::Map<&'static str, &'static [u8]> = {};\n",
        map_gz.build()
    )?;

    let mut map_lookup = phf_codegen::Map::new();
    let mut map_br = phf_codegen::Map::new();
    let mut map_gz = phf_codegen::Map::new();
    for (lang, i18n) in rauthy_i18n::build_all_common() {
        let hash = i18n.content_hash();
        map_lookup.entry(lang.as_str(), format!("{hash:?}"));

        let json = serde_json::to_string(&i18n)?;
        let name = format!("/common/{lang}_{hash}");
        let name_br = format!("{name}.br");
        let name_gz = format!("{name}.gz");
        write_compress(&name, &name_br, &name_gz, &json).await;

        map_br.entry(hash.clone(), format!("include_bytes!(\"../{name_br}\")"));
        map_gz.entry(hash, format!("include_bytes!(\"../{name_gz}\")"));
    }
    writeln!(
        hashes_map_rs,
        "pub(crate) static HASHES_COMMON: ::phf::Map<&'static str, &'static str> = {};\n",
        map_lookup.build()
    )?;
    writeln!(
        hashes_map_rs,
        "pub(crate) static I18N_COMMON_BR: ::phf::Map<&'static str, &'static [u8]> = {};\n",
        map_br.build()
    )?;
    writeln!(
        hashes_map_rs,
        "pub(crate) static I18N_COMMON_GZ: ::phf::Map<&'static str, &'static [u8]> = {};",
        map_gz.build()
    )?;

    fs::write(PATH_MAPS, hashes_map_rs).await?;

    Ok(())
}

async fn write_compress(file_name: &str, file_name_br: &str, file_name_gz: &str, json: &str) {
    let path = format!("{PATH_STATIC}{file_name}");
    println!("{path}");
    let mut file = File::create(&path).await.unwrap();
    file.write_all(json.as_bytes()).await.unwrap();
    file.sync_data().await.unwrap();

    compress_br(&path, file_name_br).await;
    compress_gzip(&path, file_name_gz).await;
}

async fn compress_br(from: &str, to: &str) {
    let reader = BufReader::new(File::open(from).await.unwrap());
    let params = brotli::EncoderParams::default().quality(async_compression::Level::Best);
    let mut compressor = BrotliEncoder::with_params(reader, params);

    let path = format!("{PATH_STATIC}{to}");
    let mut out = File::create(&path).await.unwrap();
    tokio::io::copy(&mut compressor, &mut out).await.unwrap();
    out.sync_data().await.unwrap();
    println!("{path}");
}

async fn compress_gzip(from: &str, to: &str) {
    let reader = BufReader::new(File::open(from).await.unwrap());
    let mut compressor = GzipEncoder::with_quality(reader, async_compression::Level::Best);

    let path = format!("{PATH_STATIC}{to}");
    let mut out = File::create(&path).await.unwrap();
    tokio::io::copy(&mut compressor, &mut out).await.unwrap();
    out.sync_data().await.unwrap();
    println!("{path}");
}
